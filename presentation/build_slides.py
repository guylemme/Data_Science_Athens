"""Build the seven-slide, five-minute presentation from recomputed CSV results.

Input: results/analysis.json generated by analysis_pipeline.py.
Output: root PDF, PNG previews and extracted evidence in presentation/.
Run from any directory: python presentation/build_slides.py
Requires matplotlib only. No dataset download, model execution or network access.
"""
from pathlib import Path
import json
import math
from datetime import datetime
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.backends.backend_pdf import PdfPages
from matplotlib.patches import FancyBboxPatch

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
ASSETS = HERE / "assets"
PREVIEWS = HERE / "previews"
BG = "#0b1728"
FG = "#f4f7fa"
MUTED = "#b5c5d5"
TEAL = "#47d7ba"
GOLD = "#ffca76"
PANEL = "#14273e"
plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 15})


def extract_evidence():
    """Input: fresh pipeline JSON. Output: regenerated evidence plots and results."""
    data = json.loads((ROOT / "results" / "analysis.json").read_text(encoding="utf-8"))
    temporal = data["temporal"]
    def dates(rows):
        return [datetime.fromisoformat(row["Date"]) for row in rows]
    with plt.rc_context({"font.size":10}):
        fig, axes = plt.subplots(2,1,figsize=(13,9))
        history=temporal["history"]
        test_start=datetime.fromisoformat(temporal["test_start"])
        train=[r for r in history if datetime.fromisoformat(r["Date"])<test_start][-90:]
        axes[0].plot(dates(train),[r["Observed"] for r in train],label="Training observations")
        evaluation=temporal["evaluation"]
        for col,color in [("Observed","black"),("Holt_Winters","darkorange"),("Seasonal_naive","green")]:
            axes[0].plot(dates(evaluation),[r[col] for r in evaluation],label=col.replace("_"," "),color=color,ls="--" if col=="Seasonal_naive" else "-")
        axes[0].set_title("Query 3: Forecast evaluation")
        axes[1].plot(dates(history[-120:]),[r["Observed"] for r in history[-120:]],label="Historical observations")
        future=temporal["future"]
        axes[1].plot(dates(future),[r["Predicted_PM25"] for r in future],label="Next 30 days",color="darkorange")
        axes[1].set_title("Future daily PM2.5 forecast")
        for ax in axes:
            ax.legend(fontsize=9); ax.grid(alpha=.25); ax.set_ylabel("PM2.5 (µg/m³)"); ax.set_xlabel("Date"); ax.tick_params(axis="x",labelsize=8)
        fig.tight_layout()
        forecast=ASSETS/"forecast_computed.png"
        fig.savefig(forecast,dpi=140); plt.close(fig)
        fig,axes=plt.subplots(1,2,figsize=(15,6))
        stations=data["spatial"]["stations"]
        for label in sorted({r["cluster"] for r in stations}):
            group=[r for r in stations if r["cluster"]==label]
            axes[0].scatter([r["longitude"] for r in group],[r["latitude"] for r in group],label="Noise" if label==-1 else f"Cluster {label}",marker="x" if label==-1 else "o",color="gray" if label==-1 else plt.get_cmap("tab10")(label),s=55)
        axes[0].set_aspect(1/math.cos(math.radians(sum(r["latitude"] for r in stations)/len(stations))))
        axes[0].set_xlabel("Longitude"); axes[0].set_ylabel("Latitude"); axes[0].set_title("Query 4: Geographical station clusters"); axes[0].legend(fontsize=8); axes[0].grid(alpha=.25)
        summary=data["spatial"]["summary"]
        axes[1].bar([str(r["cluster"]) for r in summary],[r["mean_PM25"] for r in summary],color="coral")
        axes[1].set_xlabel("Cluster"); axes[1].set_ylabel("Mean station PM2.5 (µg/m³)"); axes[1].set_title("Average PM2.5 by geographical cluster"); axes[1].grid(axis="y",alpha=.25)
        fig.tight_layout()
        spatial=ASSETS/"spatial_computed.png"
        fig.savefig(spatial,dpi=140); plt.close(fig)
    for old_name in ["forecast_saved.png", "spatial_saved.png"]:
        (ASSETS/old_name).unlink(missing_ok=True)
    return forecast,spatial,data


def text(fig, x, y, value, size=18, color=FG, weight="normal", **kw):
    """Input: slide and text placement. Output: positioned text artist."""
    return fig.text(x, y, value, fontsize=size, color=color, weight=weight, va="top", **kw)


def base(page, category, title, subtitle=""):
    """Input: page labels. Output: a 16:9 slide with consistent typography."""
    fig = plt.figure(figsize=(16, 9), facecolor=BG)
    text(fig, .055, .94, "ATHENS  /  AIR QUALITY", 12, TEAL, "bold")
    text(fig, .945, .94, category.upper(), 12, MUTED, ha="right")
    text(fig, .055, .85, title, 32, weight="bold")
    if subtitle:
        text(fig, .055, .768, subtitle, 16, MUTED)
    text(fig, .055, .045, "Programming for Data Science  ·  ESILV", 10, MUTED)
    text(fig, .945, .045, f"{page} / 7", 10, MUTED, ha="right")
    return fig


def panel(fig, x, y, width, height):
    """Input: rectangle geometry. Output: colored background panel."""
    fig.add_artist(FancyBboxPatch((x, y), width, height, boxstyle="round,pad=0.012,rounding_size=0.012", transform=fig.transFigure, facecolor=PANEL, edgecolor=PANEL, zorder=-1))


def metric(fig, x, y, value, label, width=.25):
    """Input: number and caption. Output: statistic card."""
    panel(fig, x, y-.14, width, .16)
    text(fig, x+.018, y, value, 30, TEAL, "bold")
    text(fig, x+.018, y-.075, label, 13, MUTED)


def plot_image(fig, path, bounds):
    """Input: original saved notebook PNG and bounds. Output: figure image."""
    ax = fig.add_axes(bounds)
    ax.imshow(plt.imread(path))
    ax.axis("off")


def make_slides():
    """Input: recomputed CSV evidence. Output: presentation figure list."""
    forecast, spatial, data = extract_evidence()
    slides = []
    f = base(1, "Research question", "Understanding air pollution in Athens")
    text(f, .055, .68, "Where is pollution concentrated?\nWhich weather conditions accompany it?\nCan we anticipate its daily evolution?", 27, FG, linespacing=1.55)
    panel(f, .66, .30, .28, .37)
    text(f, .68, .64, "ONE DATASET\nFOUR PERSPECTIVES", 15, TEAL, "bold", linespacing=1.5)
    text(f, .68, .50, "Stations\nAssociations\nForecasts\nSpatial clusters", 20, linespacing=1.5)
    text(f, .055, .27, "Guilhem LE DU  ·  Anais KAMTCHOUANG NONO\nYutong CAO  ·  Soukaina BAHAMI", 17, MUTED, linespacing=1.7)
    text(f, .055, .13, "github.com/guylemme/Data_Science_Athens", 13, TEAL)
    slides.append(f)

    f = base(2, "Data & KDD", "A multidimensional view of the city", "Air Quality Monitoring in European Cities · Kaggle · Athens subset")
    for x, val, label in [(.055,"1.73 million","hourly observations"),(.355,"64","monitoring stations"),(.655,"19","original columns")]:
        metric(f,x,.65,val,label,.275)
    text(f,.055,.43,"WHEN",13,TEAL,"bold")
    text(f,.055,.38,"May 2020 – May 2023\nHourly records → daily station averages",19,linespacing=1.6)
    text(f,.53,.43,"WHERE & WHAT",13,TEAL,"bold")
    text(f,.53,.38,"Coordinates + station identifiers\nPM2.5, PM10, NO₂, O₃ + weather",19,linespacing=1.6)
    text(f,.055,.20,"Select  →  Explore  →  Prepare  →  Mine & model  →  Visualize",21,GOLD,"bold")
    text(f,.055,.115,"Missing weather and gas measurements require explicit handling; very high PM values need interpretation.",13,MUTED)
    slides.append(f)

    f = base(3,"Query 1 · Aggregation","Compare pollution across monitoring stations", "A station-level view makes spatial differences visible before applying more complex models.")
    top=data["station_stats"][:5]
    ax=f.add_axes([.24,.29,.32,.34],facecolor=BG)
    ax.barh([r["station_name"] for r in top][::-1],[r["pm25_mean"] for r in top][::-1],color=TEAL,height=.55)
    ax.set_xlim(0,27); ax.set_xlabel("Mean hourly PM2.5 (µg/m³)",color=MUTED,labelpad=12)
    ax.tick_params(colors=FG,labelsize=12)
    for spine in ax.spines.values(): spine.set_visible(False)
    for i,r in enumerate(top[::-1]): ax.text(r["pm25_mean"]+.4,i,f'{r["pm25_mean"]:.2f}',va="center",color=FG,fontsize=12)
    text(f,.055,.67,"Five stations with the highest mean PM2.5",15,MUTED)
    metric(f,.66,.63,"23.03 µg/m³","joint highest mean: two stations",.27)
    metric(f,.66,.40,"8,333 hours","above 25 µg/m³ at ATHINAS",.27)
    text(f,.055,.205,"Also calculated: maximum PM2.5 and mean NO₂ per station.",15,MUTED)
    text(f,.055,.15,"Interpretation: the 25 µg/m³ cutoff is a project indicator on hourly data, not a regulatory compliance test.",13,GOLD)
    text(f,.055,.105,"Compare coverage as well as concentrations; raw exceedance counts depend on the number of observed hours.",13,MUTED)
    slides.append(f)

    f = base(4,"Query 2 · Apriori","Low wind accompanies high PM2.5", "Daily station records → quartile categories → one-hot encoding → association rules")
    ax=f.add_axes([.20,.25,.36,.40],facecolor=BG)
    names=["High temperature","Low temperature","High humidity","Low wind speed"]
    singleton_lifts={r["antecedents"][0]:r["lift"] for r in data["rules"] if len(r["antecedents"])==1}
    lifts=[singleton_lifts[k] for k in ["Temperature_Level_High","Temperature_Level_Low","Humidity_Level_High","Wind_Speed_Level_Low"]]
    ax.barh(names,lifts,color=["#476480"]*3+[TEAL],height=.52)
    ax.axvline(1,color=GOLD,ls="--",lw=1.5)
    ax.set_xlim(0,2.1)
    ax.set_xlabel("Lift (1 = independence)",color=MUTED,labelpad=12)
    ax.tick_params(colors=FG,labelsize=13)
    for spine in ax.spines.values(): spine.set_visible(False)
    for i,v in enumerate(lifts): ax.text(v+.035,i,f"{v:.2f}",color=FG,va="center",fontsize=14)
    metric(f,.66,.64,"44.88%","confidence: high PM2.5 given low wind",.27)
    text(f,.66,.40,"90 frequent itemsets\n300 rules · 10 target rules",19,linespacing=1.6)
    text(f,.66,.25,"Minimum support: 5%\nMinimum confidence: 10%",15,MUTED,linespacing=1.7)
    text(f,.055,.13,"“High” means above the dataset’s third quartile. Association does not establish causation.",14,GOLD)
    text(f,.055,.085,"Evidence: recomputed original CSV; lift values are rounded for presentation.",11,MUTED)
    slides.append(f)

    f = base(5,"Query 3 · Forecasting","Predict daily PM2.5, then test the prediction", "Holt-Winters: additive damped trend + 7-day seasonality · final 30 days reserved for testing")
    plot_image(f,forecast,[.04,.16,.61,.54])
    metric(f,.70,.65,"4.04 µg/m³","Holt-Winters test MAE",.24)
    metric(f,.70,.43,"4.34 µg/m³","seasonal-naive test MAE",.24)
    text(f,.70,.22,"RMSE: 4.83 vs 5.41\nForecast horizon: 30 days",16,MUTED,linespacing=1.6)
    text(f,.055,.105,"Recomputed test results show a modest improvement over repeating the previous week; lower error is better.",13,GOLD)
    text(f,.055,.075,"The forecast starts after 29 May 2023. It is a historical model demonstration, not a forecast for today.",11,MUTED)
    slides.append(f)

    f = base(6,"Query 4 · Spatial clustering","Group nearby stations and compare their PM2.5", "DBSCAN with haversine distance · radius 2 km · minimum 3 stations in a dense neighborhood")
    text(f,.055,.67,"5 geographical groups",24,TEAL,"bold")
    text(f,.53,.67,"32 of 64 stations outside groups",24,GOLD,"bold")
    plot_image(f,spatial,[.04,.19,.92,.43])
    text(f,.055,.15,"Clustering uses location only. PM2.5 is summarized afterwards; groups are not pollution classes.",14,FG)
    text(f,.055,.095,"Noise means spatial isolation at the selected settings, not a faulty measurement. Results depend on radius and density.",12,MUTED)
    slides.append(f)

    f = base(7,"Dashboard & takeaways","Four analyses in one interactive dashboard", "Offline HTML + Plotly · Demo: stations → association rules → forecasts → geographical clusters")
    panel(f,.055,.26,.43,.42)
    text(f,.075,.65,"WHAT THE DASHBOARD CONNECTS",14,TEAL,"bold")
    text(f,.075,.57,"Compare stations\nInspect weather associations\nReview forecasts against observations\nExplore geographical groups",20,linespacing=1.7)
    text(f,.55,.65,"WHAT WE LEARN",14,TEAL,"bold")
    text(f,.55,.57,"Low wind is associated with high PM2.5.\nA weekly forecasting model improves\nslightly on the baseline in this test.\nSpatial proximity provides context\nfor comparing station pollution.",18,linespacing=1.6)
    text(f,.055,.18,"Limits: associations are not causal; one holdout period; clustering parameter sensitivity; missing values and extremes.",13,GOLD)
    text(f,.055,.105,"Source: Kaggle · yekenot/air-quality-monitoring-in-european-cities · recomputed from original CSV",11,MUTED)
    text(f,.055,.075,"CSV SHA-256: "+data["metadata"]["source_sha256"][:24]+"… · full provenance in results/analysis.json",10,MUTED)
    slides.append(f)
    return slides


def main():
    """Input: recomputed CSV JSON. Output: PDF and seven PNG previews."""
    ASSETS.mkdir(parents=True,exist_ok=True)
    PREVIEWS.mkdir(parents=True,exist_ok=True)
    slides=make_slides()
    output=ROOT/"Soukaina_Bahami_slides.pdf"
    with PdfPages(output,metadata={"Title":"Air Quality Monitoring in Athens", "Author":"Guilhem LE DU; Anais KAMTCHOUANG NONO; Yutong CAO; Soukaina BAHAMI", "Subject":"Programming for Data Science final project"}) as pdf:
        for i,fig in enumerate(slides,1):
            pdf.savefig(fig,facecolor=fig.get_facecolor())
            fig.savefig(PREVIEWS/f"slide-{i:02}.png",dpi=100,facecolor=fig.get_facecolor())
            plt.close(fig)
    print(f"Generated {output.name}: {len(slides)} slides")


if __name__=="__main__":
    main()
